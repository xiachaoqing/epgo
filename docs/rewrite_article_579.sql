<h2>二、术语不是拦路虎，先分清“必须懂”和“暂时懂个大概”</h2>

<p>很多学生一碰到科普文，就被术语吓住。比如 climate change、photosynthesis、ecosystem、carbon dioxide、renewable energy 这些词，单看就比 everyday English 更有压迫感。</p>

<p>可真正有效的阅读，并不是要求孩子一上来就把所有术语都查到最细，而是先判断：哪些是文章的核心概念，必须抓住；哪些只是支撑信息，先大概知道就够了。</p>

<p>例如一篇讲植物的文章，如果反复出现 photosynthesis，那它就是核心概念；如果某个稀有植物名只出现一次，它对理解主旨的重要性就没那么高。</p>

<ul>
<li><strong>先圈反复出现的术语</strong>：重复出现的词，通常就是文章的骨架</li>
<li><strong>先给它一个能理解的大意</strong>：不必一开始就追求教科书级精确定义</li>
<li><strong>边读边修正理解</strong>：很多术语的真正含义，是随着后文解释逐步清楚的</li>
</ul>

<p>这一步特别重要，因为很多学生一上来就逐词死查，最后把阅读节奏完全打断。术语当然要重视，但顺序不能错：先知道谁最重要，再决定查多深。</p>

<h2>三、长句不是越拆越碎，而是先找“主干”</h2>

<p>科普文里最让人头疼的，常常不是术语，而是长句。因为一个句子里会塞进定义、原因、补充说明和结果，孩子一旦试图每个词都逐个翻译，脑子很快就乱了。</p>

<p>真正有效的方法，不是从头到尾硬翻，而是先找主干：谁怎么样了？发生了什么？核心动作是什么？</p>

<p>比如这样一句：<br>
<em>Scientists found that tiny changes in ocean temperature can affect the movement of fish.</em></p>

<p>如果孩子一上来就纠结 tiny、ocean、affect、movement，每个都想讲清楚，整句节奏就散了。可如果先抓主干：<br>
<strong>Scientists found that ... can affect ...</strong><br>
后面的细节再往上挂，整句就顺了。</p>

